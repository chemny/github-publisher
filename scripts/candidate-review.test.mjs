#!/usr/bin/env node
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
const checker=fileURLToPath(new URL('./publish-check.mjs',import.meta.url));
const h=b=>createHash('sha256').update(b).digest('hex');
function fixture() {
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'candidate-review-'));const root=path.join(temp,'package');fs.mkdirSync(root);
 fs.writeFileSync(path.join(root,'SKILL.md'),'---\nname: fixture\ndescription: Use when testing content review.\n---\n');
 fs.writeFileSync(path.join(root,'LICENSE'),'MIT License\nCopyright (c) 2026 Actual Owner\n');
 const quote='Keep the explicitly reviewed fixture owner and source notices; no publication.';
 const source=path.join(temp,'user-confirmation.txt');fs.writeFileSync(source,quote);
 const receipt=path.join(temp,'receipt.json');
 const scan=(file, cwd=root)=>{
  const p=spawnSync(process.execPath,[checker,'--report=report.json',...(file?['--candidate-review='+file]:[])],{cwd,encoding:'utf8'});
  assert.notEqual(p.status,null,p.stderr);return {report:JSON.parse(fs.readFileSync(path.join(cwd,'report.json'),'utf8')),status:p.status};
 };
 const base=scan().report;const finding=base.results.find(x=>x.reviewId&&x.detail.startsWith('LICENSE:'));assert.ok(finding);
 const record={schemaVersion:1,kind:'candidate-content-review',candidateDigest:base.attributionReview.candidateDigest,decisions:[{reviewId:finding.reviewId,decision:'keep',revoked:false,userQuote:quote,confirmedAt:new Date().toISOString(),sourceEvidence:{path:source,sha256:h(fs.readFileSync(source))}}]};
 const save=()=>fs.writeFileSync(receipt,JSON.stringify(record));save();
 return {temp,root,source,receipt,scan,record,save,finding};
}
const reused=(r,id)=>r.results.some(x=>x.reviewId===id&&x.decisionReused);
const pending=r=>r.results.filter(x=>x.reviewId&&x.level==='WARNING');
const cases=[
 ['valid explicit receipt',f=>assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),true)],
 ['no explicit receipt means no reuse',f=>assert.equal(reused(f.scan().report,f.finding.reviewId),false)],
 ['source bytes changed',f=>{fs.appendFileSync(f.source,' changed');assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['source quote not found',f=>{f.record.decisions[0].userQuote='Someone said something else';f.save();assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['wrong source digest',f=>{f.record.decisions[0].sourceEvidence.sha256='0'.repeat(64);f.save();assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['revoked decision',f=>{f.record.decisions[0].revoked=true;f.save();assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['changed candidate notice',f=>{fs.appendFileSync(path.join(f.root,'LICENSE'),'\nCopyright (c) 2026 Another Owner\n');assert.ok(pending(f.scan(f.receipt).report).length);}],
 ['new unrelated bytes invalidate whole-candidate receipt',f=>{fs.writeFileSync(path.join(f.root,'extra.txt'),'new');assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['malformed receipt',f=>{fs.writeFileSync(f.receipt,'{bad');assert.equal(f.scan(f.receipt).report.attributionReview.candidateReceipt.status,'invalid');}],
 ['missing confirmation source',f=>{fs.unlinkSync(f.source);assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['receipt inside candidate refused',f=>{const p=path.join(f.root,'approval.json');fs.writeFileSync(p,JSON.stringify(f.record));assert.equal(f.scan(p).report.attributionReview.candidateReceipt.status,'invalid');}],
 ['confirmation source inside candidate refused',f=>{const p=path.join(f.root,'user.txt');fs.writeFileSync(p,f.record.decisions[0].userQuote);f.record.decisions[0].sourceEvidence={path:p,sha256:h(fs.readFileSync(p))};f.record.candidateDigest=f.scan().report.attributionReview.candidateDigest;f.save();assert.equal(reused(f.scan(f.receipt).report,f.finding.reviewId),false);}],
 ['same byte package relocated with explicit external receipt',f=>{const other=path.join(f.temp,'copied');fs.cpSync(f.root,other,{recursive:true});assert.equal(reused(f.scan(f.receipt,other).report,f.finding.reviewId),true);}],
 ['new real attribution still detected',f=>{fs.writeFileSync(path.join(f.root,'credits.md'),'Generated by Real Studio\n');const a=f.scan(f.receipt).report;assert.ok(pending(a).some(x=>x.detail.startsWith('credits.md:')));}],
 ['one copyright file produces one combined review',f=>assert.equal(pending(f.scan().report).filter(x=>x.detail.startsWith('LICENSE:')).length,1)],
 ['example email is not a domain allowlist',f=>{fs.writeFileSync(path.join(f.root,'contact.md'),'Example: privacy@company.com\nContact: privacy@company.com\n');assert.ok(pending(f.scan().report).some(x=>x.detail.startsWith('contact.md:')));}],
 ['code blocks remain scanned',f=>{fs.writeFileSync(path.join(f.root,'sample.md'),'```text\nGenerated by Real Studio\n```');assert.ok(pending(f.scan().report).some(x=>x.detail.startsWith('sample.md:')));}],
 ['receipt does not authorize publication',f=>assert.equal(f.scan(f.receipt).report.attributionReview.publicationAuthorized,false)],
 ['content receipt cannot suppress secret hard failures',f=>{
  fs.writeFileSync(path.join(f.root,'sample.md'),'Example: demo@company.com\n'+'sk-'+'a'.repeat(32)+'\n');
  f.record.candidateDigest=f.scan().report.attributionReview.candidateDigest;f.save();const a=f.scan(f.receipt);
  assert.ok(a.report.results.some(x=>x.level==='FAIL'&&x.title.startsWith('Possible secret:')));assert.equal(a.status,1);
 }],
];
for(const [name,body] of cases)test(name,()=>{const f=fixture();try{body(f);}finally{fs.rmSync(f.temp,{recursive:true,force:true});}});
test('candidate receipt cannot approve Git history identity',()=>{
 const f=fixture();try{
  const git=(...a)=>{const q=spawnSync('git',a,{cwd:f.root,encoding:'utf8'});assert.equal(q.status,0,q.stderr);};
  git('init');git('add','SKILL.md','LICENSE');git('-c','user.name=Fixture Owner','-c','user.email=real@business.org','-c','commit.gpgsign=false','commit','-m','fixture');
  const a=f.scan().report;const finding=a.results.find(x=>x.title.startsWith('Git history identity'));assert.ok(finding);
  f.record.candidateDigest=a.attributionReview.candidateDigest;f.record.decisions[0].reviewId=finding.reviewId;f.save();assert.equal(reused(f.scan(f.receipt).report,finding.reviewId),false);
 }finally{fs.rmSync(f.temp,{recursive:true,force:true});}
});
test('report path cannot exclude and overwrite an existing payload file',()=>{
 const f=fixture();try{
  const p=path.join(f.root,'LICENSE');const before=fs.readFileSync(p);
  const a=spawnSync(process.execPath,[checker,'--report=LICENSE'],{cwd:f.root,encoding:'utf8'});
  assert.equal(a.status,2);assert.match(a.stderr,/no file overwritten/);assert.deepEqual(fs.readFileSync(p),before);
 }finally{fs.rmSync(f.temp,{recursive:true,force:true});}
});
test('report symlink cannot overwrite an external file',()=>{
 const f=fixture();try{
  const p=path.join(f.temp,'outside.txt');fs.writeFileSync(p,'unchanged');fs.symlinkSync(p,path.join(f.root,'linked-report.json'));
  const a=spawnSync(process.execPath,[checker,'--report=linked-report.json'],{cwd:f.root,encoding:'utf8'});
  assert.equal(a.status,2);assert.equal(fs.readFileSync(p,'utf8'),'unchanged');
 }finally{fs.rmSync(f.temp,{recursive:true,force:true});}
});
test('prior report is not exempt from secret scanning',()=>{
 const f=fixture();try{
  const p=path.join(f.root,'report.json');const report=JSON.parse(fs.readFileSync(p,'utf8'));
  report.syntheticRisk='sk-'+'a'.repeat(32);fs.writeFileSync(p,JSON.stringify(report));
  const result=f.scan(f.receipt);
  assert.ok(result.report.results.some(x=>x.level==='FAIL'&&x.title.startsWith('Possible secret:')));
  assert.equal(result.status,1);
 }finally{fs.rmSync(f.temp,{recursive:true,force:true});}
});
test('actual scan-time payload mutation blocks even an approved candidate',()=>{
 const f=fixture();try{
  const hook=path.join(f.temp,'inject.mjs');
  fs.writeFileSync(hook,`import fs from 'node:fs';import path from 'node:path';const original=fs.readFileSync;let injected=false;fs.readFileSync=function(file,...args){const value=original.call(fs,file,...args);if(!injected&&String(file)===path.join(process.cwd(),'LICENSE')&&args[0]==='utf8'){injected=true;fs.writeFileSync(path.join(process.cwd(),'late-arrival.txt'),'synthetic concurrent write');}return value;};`);
  const p=spawnSync(process.execPath,['--import',pathToFileURL(hook).href,checker,'--report=report.json','--candidate-review='+f.receipt],{cwd:f.root,encoding:'utf8'});
  assert.equal(p.status,1,p.stderr);const a=JSON.parse(fs.readFileSync(path.join(f.root,'report.json'),'utf8'));
  assert.ok(a.results.some(x=>x.level==='FAIL'&&x.title==='Candidate changed during scan'));
  assert.equal(a.attributionReview.candidateReceipt.status,'invalidated-during-scan');
  assert.equal(reused(a,f.finding.reviewId),false);
 }finally{fs.rmSync(f.temp,{recursive:true,force:true});}
});
