#!/usr/bin/env node
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { inspectAttribution } from './review-findings.mjs';
const license = fs.readFileSync(new URL('../evals/fixtures/licenses/Apache-2.0.txt',import.meta.url),'utf8');
const benign = [
 ['passive grammar', 'Example error: "The decision was made by the team to move forward with the strategy that was agreed upon."'],
 ['user content', 'Product content created by users gets shared on external platforms, bringing new users back to the product.'],
 ['value', '**Impact**: The value created by validating this assumption AND the number of customers affected'],
 ['data analysis', 'A counterintuitive behavioral pattern or motivation derived from the data'],
 ['feasibility', '**Feasibility**: Can it be built with existing technology? Are there integration risks?'],
 ['example email', '- `$CONTACT_EMAIL`: Email for privacy inquiries (e.g., privacy@company.com)'],
 ['standard license', license],
];
for (const [name,text] of benign) test(`no false review: ${name}`,()=>{
 const a=inspectAttribution('materials.md',text);assert.equal(a.review.length,0);assert.ok(a.standardLicense || a.informational.length);
});
const real = [
 ['actual maker','This Skill was made by Real Studio.'],
 ['actual creator','This Skill was created by Acme.'],
 ['real source','This method is derived from Acme Toolkit.'],
 ['explicit adaptation','Method adapted from the public security plugin.'],
 ['tool credit','Built with ToolKit Pro.'],
 ['same-domain real contact','Contact: privacy@company.com'],
 ['real email','For support contact actual@business.org.'],
 ['author field','Author: Real Owner'],
 ['copyright','Copyright (c) 2026 Real Owner'],
 ['code block is not exempt','```text\nGenerated by Real Studio\n```'],
 ['Example is a possible actual name','Generated by Example Studio'],
 ['Chinese credit','制作方：某工作室'],
 ['changed license',license+'\nGenerated by Real Studio\n'],
 ['unrecognized license','License material altered; derived from Private Vendor\n'],
 ['unknown context stays review','Something was made by Something Else.'],
];
for (const [name,text] of real) test(`retain real/unknown review: ${name}`,()=>assert.ok(inspectAttribution('LICENSE',text).review.length>0));
for (const [name,text] of benign.slice(0,6)) test(`benign text cannot mask real credit: ${name}`,()=>{
 const a=inspectAttribution('README.md',text+' Generated by Real Studio.');assert.ok(a.review.some(x=>x.label.includes('ownership')||x.label.includes('watermark')));
});
test('example marker applies to that address only',()=>assert.equal(inspectAttribution('a.md','Example: demo@business.org; contact real@business.org').review.filter(x=>x.label==='email address').length,1));
test('neutral disclaimer does not erase appended attribution',()=>assert.ok(inspectAttribution('a.md','Third-party names remain subject to their original terms. Generated by Real Studio').review.length));
test('standard license normalization permits CRLF only, added content is rechecked',()=>{
 assert.equal(inspectAttribution('license.txt',license.replace(/\n/g,'\r\n')).standardLicense,'Apache-2.0');
 assert.equal(inspectAttribution('license.txt',license+'\nGenerated by Someone\n').standardLicense,null);
});
test('one source file keeps every category and location',()=>{
 const a=inspectAttribution('LICENSE','Copyright (c) 2026 Real Owner\nAdapted from Acme\nContact: real@business.org');
 assert.ok(a.review.some(x=>x.kind==='third-party'));assert.ok(a.review.some(x=>x.kind==='identity'));assert.ok(a.review.some(x=>x.line===3));
});
