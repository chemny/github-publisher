#!/usr/bin/env node
/** Deterministic attribution candidates, not a legal or semantic certification. */
import { createHash } from 'node:crypto';
const hash = text => createHash('sha256').update(text).digest('hex');
// Reviewed, complete Apache-2.0 body. Exact normalized content, never a path allowlist.
const standardLicenses = new Map([
  ['283ea6cc2997a1a70da0049e09adf9317bb60ca1b51279b65196b83a69e1996b', 'Apache-2.0'],
]);
export const thirdPartyPatterns = [
  ['external attribution / reuse statement', /\b(?:adapted from|derived from|forked from|ported from|originally (?:from|by|written by)|copied from)\b|(?:改编自|衍生自|移植自|源自|fork\s*自)/i],
  ['copyright or trademark notice', /(?:©|\(c\)\s*\d{4}|all rights reserved|registered trademark|™|®|版权所有|著作权|保留所有权利)/i],
  ['external license terms', /(?:original (?:license|terms)|under (?:its|their|the original) license|subject to .{0,30}license|原始(?:协议|许可|条款)|第三方.{0,8}(?:协议|许可|条款))/i],
  ['generated-by or third-party ownership language', /\b(?:generated by|created by|made by|owned by|property of|courtesy of)\b|(?:归.{0,8}所有|版权所有者)|(?:^|\n)\s*由(?!生图工具|专业生图|图像生成工具).{1,24}(?:生成|创建|制作)/i],
];
const placeholder = '(?:<[^>]+>|\\{\\{[^}]+\\}\\}|\\[[^\\]]*(?:author|name|email|username|handle)[^\\]]*\\]|your[-_ ]?(?:name|email|username)|example|placeholder|todo|tbd|n/?a|none|unknown)';
export const identityPatterns = [
  ['author or maintainer field', new RegExp(`(?:^|\\n)\\s*(?:author|authors|maintainers?|creator|created by|written by|owner|contact|作者|维护者|创建者|联系人)\\s*[:=]\\s*(?!\\s*${placeholder})\\S`, 'i')],
  ['copyright holder identity', new RegExp(`(?:copyright\\s*(?:\\(c\\)|©)?|版权所有)\\s*\\d{4}(?:-\\d{4})?\\s+(?!\\s*${placeholder})\\S`, 'i')],
  ['email address', /\b[A-Z0-9._%+-]+@(?!users\.noreply\.github\.com\b|noreply\.github\.com\b|example\.(?:com|org|net)\b|email\b)[A-Z0-9.-]+\.[A-Z]{2,}\b/i],
  ['personal username or social handle', /(?:^|\n)\s*(?:github|twitter|x|weibo|bilibili|handle|username|user|用户名|账号|社交账号)\s*[:=]\s*@?[A-Za-z0-9_.-]{3,}/i],
  ['generator or tool watermark', /\b(?:generated by|generated with|created with|made with|built with|scaffolded by|powered by|ai-generated by|written with)\b|(?:^|\n)\s*(?:生成工具|制作工具|生成者|制作方)\s*[:：]|(?:^|\n)\s*由(?!生图工具|专业生图|图像生成工具).{1,24}(?:生成|创建|制作|驱动)/i],
];

function nonAttribution(line, match, label) {
  const left = line.slice(0, match.index).replace(/[`*_]/g, '');
  const right = line.slice(match.index + match[0].length).replace(/^[`*_\s]+/, '');
  const term = match[0].trim().toLowerCase();
  if (term === 'made by' && /\b(?:decision|choice|mistake|request|recommendation)\s+(?:was|is|were|are|being)\s*$/i.test(left)
      && /^(?:the\s+)?(?:team|users?|customers?|participants?)\b/i.test(right)) return 'ordinary passive-voice description';
  if (term === 'created by' && /\b(?:content|posts?|comments?|reviews?)\s*$/i.test(left)
      && /^(?:the\s+)?users?\b/i.test(right)) return 'user-generated business content';
  if (term === 'created by' && /\b(?:value|benefits?|impact|revenue)\s*$/i.test(left)
      && /^(?:validating|testing|learning)\b/.test(right)) return 'value or impact explanation';
  if (term === 'derived from' && /\b(?:patterns?|motivations?|insights?|conclusions?|findings?)\s*$/i.test(left)
      && /^(?:the\s+)?(?:data|observations|user research)\b/i.test(right)) return 'analytical inference from data';
  if (term === 'built with' && /\b(?:can|could|would|should)\b[^.!?\n]{0,40}\bbe\s*$/i.test(left)
      && /^existing technology\b/i.test(right)) return 'feasibility question';
  if (label === 'email address' && /(?:\be\.g\.,?\s*|\b(?:example|sample)(?:\s+(?:email|address))?\s*[:,]\s*|例如[：:]?\s*|示例(?:邮箱)?[：:]\s*)$/i.test(left)) return 'explicit illustrative email';
  return null;
}

export function inspectAttribution(rel, content, { thirdParty = true, identity = true } = {}) {
  const normalized = content.replace(/\r\n?/g, '\n');
  const standard = standardLicenses.get(hash(normalized.trim()));
  if (standard) return { standardLicense: standard, review: [], informational: [], evidence: [rel, [normalized.trim()]] };
  const review = [], informational = [];
  const groups = [...(thirdParty ? [['third-party', thirdPartyPatterns]] : []), ...(identity ? [['identity', identityPatterns]] : [])];
  const lines = normalized.split('\n').map(line => line
    .replace(/third-?party names(?: and (?:trademarks|brands))? remain subject to their original terms\.?/gi, '')
    .replace(/第三方名称(?:及商标)?仍?受其原始(?:条款|协议)约束[。]?/g, ''));
  for (let n = 0; n < lines.length; n++) {
    const line = lines[n];
    for (const [kind, patterns] of groups) {
      for (const [label, pattern] of patterns) {
        const re = new RegExp(pattern.source, pattern.flags.replace('g', '') + 'g');
        for (const match of line.matchAll(re)) {
          const reason = nonAttribution(line, match, label);
          const item = { kind, label, line: n + 1, reason: reason ?? 'unresolved attribution/identity candidate' };
          (reason ? informational : review).push(item);
        }
      }
    }
  }
  // One review per file, with all categories/locations preserved. No whole-line exemptions.
  const evidenceLines = [...new Set(review.map(x => lines[x.line - 1].trim()))].sort();
  return { standardLicense: null, review, informational, evidence: [rel, evidenceLines] };
}
